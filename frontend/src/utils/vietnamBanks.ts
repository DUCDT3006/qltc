export function findBankByCode(code?: string): VietnamBank | undefined {
  if (!code) return undefined;
  const upper = code.toUpperCase();
  return VIETNAM_BANKS.find(b => 
    b.code.toUpperCase() === upper || 
    b.shortName.toUpperCase() === upper ||
    (upper === 'HDBANK' && b.code === 'HDB') ||
    (upper === 'VIETINBANK' && b.code === 'ICB') ||
    (upper === 'VIETCOMBANK' && b.code === 'VCB') ||
    (upper === 'MBBANK' && b.code === 'MB')
  );
}

export function generateVietQrUrl(params: {
  binOrBankCode: string;
  accountNumber: string;
  accountHolder?: string;
  amount?: number;
  description?: string;
  template?: 'compact' | 'compact2' | 'qr_only' | 'print';
}): string {
  const { binOrBankCode, accountNumber, accountHolder, amount, description, template = 'compact2' } = params;
  
  // Tìm BIN chuẩn nếu truyền vào bankCode
  const bank = findBankByCode(binOrBankCode);
  const targetBin = bank?.bin || binOrBankCode;
  
  let url = `https://img.vietqr.io/image/${targetBin}-${accountNumber}-${template}.png`;
  const query = new URLSearchParams();
  
  if (amount && amount > 0) {
    query.set('amount', Math.round(amount).toString());
  }
  if (description && description.trim()) {
    query.set('addInfo', description.trim());
  }
  if (accountHolder && accountHolder.trim()) {
    query.set('accountName', accountHolder.trim().toUpperCase());
  }
  
  const qs = query.toString();
  return qs ? `${url}?${qs}` : url;
}
